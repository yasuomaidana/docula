/// Typed pipeline failure hierarchy.
#[derive(Debug, Error)]
pub enum DoculaPipelineError {
    /// Core domain error.
    #[error("Core error: {0}")]
    Core(#[from] DoculaError),

    /// Preprocessing and rasterization error.
    #[error("Preprocessing error: {0}")]
    Preprocess(#[from] PreprocessError),

    /// Ingestion and inspection error.
    #[error("Ingest error: {0}")]
    Ingest(#[from] IngestError),

    /// OCR recognition and layout error.
    #[error("OCR error: {0}")]
    Ocr(#[from] OcrError),

    /// Schema compilation and validation error.
    #[error("Schema error: {0}")]
    Schema(#[from] SchemaError),

    /// LLM inference or logits masking error.
    #[error("LLM inference error: {0}")]
    Llm(#[from] LlmError),

    /// Human-in-the-loop triage error.
    #[error("HITL error: {0}")]
    Hitl(#[from] HitlError),

    /// Optical barcode and QR scanning error.
    #[error("Optical code error: {0}")]
    VisionCodes(#[from] OpticalCodeError),

    /// JSON serialization or deserialization error.
    #[error("JSON error: {0}")]
    Json(#[from] serde_json::Error),

    /// General I/O error reading input document files.
    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),

    /// Generic pipeline execution failure.
    #[error("Pipeline execution failure: {0}")]
    ExecutionFailure(String),
}

/// Operational configuration parameters for [`DoculaPipeline`].
#[derive(Clone, Debug)]
pub struct PipelineConfig {
    /// Rasterization resolution in dots-per-inch.
    pub dpi: u32,
    /// Maximum self-repair retry attempts on domain validation failures.
    pub max_repair_attempts: usize,
    /// Minimum acceptable token confidence score before routing to triage.
    pub min_token_confidence: f32,
    /// Whether deterministic compliance redaction is executed.
    pub enable_redaction: bool,
    /// Whether 1D/2D optical codes are detected and parsed.
    pub enable_vision_codes: bool,
    /// Whether few-shot exemplars are injected into the prompt.
    pub enable_exemplars: bool,
    /// Whether retrieval-augmented generation (RAG) is executed to enrich prompt context.
    pub enable_rag: bool,
    /// Operating validation mode dictating whether soft validation errors yield data.
    pub validation_mode: ValidationMode,
}

impl Default for PipelineConfig {
    fn default() -> Self {
        Self {
            dpi: 150,
            max_repair_attempts: 3,
            min_token_confidence: 0.85,
            enable_redaction: true,
            enable_vision_codes: true,
            enable_exemplars: true,
            enable_rag: false,
            validation_mode: ValidationMode::Strict,
        }
    }
}

/// End-to-end extraction result payload emitted by [`DoculaPipeline`].
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ExtractionResult<T> {
    /// Caller-provided or generated document identifier.
    pub document_id: String,
    /// Detailed validation outcome distinguishing strict passes, soft passes, and syntax errors.
    pub outcome: ValidationOutcome<T>,
    /// Strongly typed domain entity matching target schema (populated in Soft/Permissive modes or on Strict pass).
    pub data: Option<T>,
    /// Raw JSON string generated by the constrained language model.
    pub raw_json: String,
    /// Estimated confidence score $[0.0, 1.0]$.
    pub confidence: f32,
    /// Decoded barcodes, QR codes, and financial metadata.
    pub optical_codes: Vec<OpticalCodeResult>,
    /// Formatted spatial layout text extracted from the document.
    pub formatted_text: String,
    /// Total number of autoregressive repair attempts executed.
    pub repair_attempts: usize,
    /// Whether this extraction was flagged and enqueued for human specialist review.
    pub routed_to_triage: bool,
    /// Explicit triage rejection reasons, if routed to review.
    pub triage_reasons: Vec<String>,
    /// Whether RAG grounding was successfully applied during extraction.\
    pub rag_applied: bool,
    /// Chunks retrieved by the RAG subsystem, if RAG is enabled.
    pub rag_retrieved_chunks: Vec<DocumentChunk>,
}

/// High-level sovereign document intelligence pipeline facade.
pub struct DoculaPipeline {
    config: PipelineConfig,
    router: DocumentRouter,
    rasterizer: TinySkiaRasterizer,
    office_rasterizer: OfficeRasterizer,
    ocr_engine: Arc<dyn OcrEngine>,
    code_detector: OpticalCodeDetector,
    compliance_redactor: ComplianceRedactor,
    _exemplar_pool: ExemplarPool,
    triage_gate: TriageGate,
    triage_queue: TriageQueue,
    llm_backend: Arc<dyn LlmBackend>,
    rag_retriever: Option<RagRetriever>,
}

impl Default for DoculaPipeline {
    fn default() -> Self {
        Self::new()
    }
}

impl DoculaPipeline {
    /// Creates a default `DoculaPipeline` equipped with pure-Rust mock backends.
    #[must_use]
    pub fn new() -> Self {
        Self {
            config: PipelineConfig::default(),
            router: DocumentRouter::new(),
            rasterizer: TinySkiaRasterizer::new(),
            office_rasterizer: OfficeRasterizer::new(),
            ocr_engine: Arc::new(MockOcrEngine::new()),
            code_detector: OpticalCodeDetector::new(),
            compliance_redactor: ComplianceRedactor::default(),
            _exemplar_pool: ExemplarPool::new(),
            triage_gate: TriageGate::new(0.85),
            triage_queue: TriageQueue::new(),
            llm_backend: Arc::new(MockLlmBackend::new()),
            rag_retriever: None,
        }
    }

    /// Creates a customizable builder for configuring `DoculaPipeline` components.
    #[must_use]
    pub fn builder() -> DoculaPipelineBuilder {
        DoculaPipelineBuilder::default()
    }

    /// Returns a reference to the active pipeline configuration.
    #[inline]
    pub fn config(&self) -> &PipelineConfig {
        &self.config
    }

    /// Returns a reference to the active HITL triage queue.
    #[inline]
    pub fn triage_queue(&self) -> &TriageQueue {
        &self.triage_queue
    }

    /// Executes end-to-end extraction over a [`DocumentSource`] using an automatically inferred document identifier.
    ///
    /// This method is an ergonomic entrypoint for callers who do not have an upstream tracking identifier
    /// and simply wish to parse a document into a strongly typed domain entity `T`. The document identifier
    /// is automatically inferred via [`DocumentSource::infer_document_id`]:
    /// - For file paths, it uses the filename stem (e.g. `"invoice-2026-001"`).
    /// - For in-memory bytes, it computes a deterministic SHA-256 fingerprint (e.g. `"doc-<16-hex-chars>"`).
    /// - For batch sources, it derives a collective batch identifier.
    ///
    /// For workflows where an external orchestrator, message queue, or database supplies a specific identifier,
    /// use [`process_document`](Self::process_document).
    ///
    /// # Example
    /// ```rust,no_run
    /// # use docula::{DoculaPipeline, DocumentSource, docula_model};
    /// # docula_model! {
    /// #     pub struct SimpleInvoice {
    /// #         pub total: f64,
    /// #     }
    /// # }
    /// # async fn run() -> Result<(), Box<dyn std::error::Error>> {
    /// let pipeline = DoculaPipeline::new();
    /// let source = DocumentSource::from_image_path("assets/invoice_001.png");
    ///
    /// // Inferred document_id: "invoice_001"
    /// let result = pipeline.process::<SimpleInvoice>(&source).await?;
    /// assert_eq!(result.document_id, "invoice_001");
    /// # Ok(())
    /// # }
    /// ```
    pub async fn process<T>(
        &self,
        source: &DocumentSource,
    ) -> Result<ExtractionResult<T>, DoculaPipelineError>
    where
        T: DocuValidate + schemars::JsonSchema + DeserializeOwned + Serialize + Send + Sync + Clone,
    {
        let inferred_id = source.infer_document_id();
        self.process_document(&inferred_id, source).await
    }

    /// Executes end-to-end extraction over a [`DocumentSource`] with an explicitly specified document identifier.
    ///
    /// Use this method when an upstream system (e.g. message queue, database ID, external workflow engine)
    /// provides the canonical tracking identifier.
    pub async fn process_document<T>(
        &self,
        document_id: &str,
        source: &DocumentSource,
    ) -> Result<ExtractionResult<T>, DoculaPipelineError>
    where
        T: DocuValidate + schemars::JsonSchema + DeserializeOwned + Serialize + Send + Sync + Clone,
    {
        let routing_report = self.router.route_source(source)?;
        let first_route = routing_report.routes.first();

        let (mut buffer, mut spans) = match first_route {
            Some(PageRoute::BornDigital { text_layer, .. }) if !source.is_pdf() => {
                let spans = text_layer.clone();
                let buf = self
                    .office_rasterizer
                    .render_spans(&spans, 0, self.config.dpi)
                    .map_err(DoculaPipelineError::Preprocess)?;
                (buf, spans)
            }
            Some(PageRoute::BornDigital { text_layer, .. }) => {
                let buf = self.render_or_load_source(source)?;
                let spans = text_layer.clone();
                (buf, spans)
            }
            _ => {
                let buf = self.render_or_load_source(source)?;
                let spans = self.ocr_engine.extract_spans(&buf.image)?;
                (buf, spans)
            }
        };

        let optical_codes = if self.config.enable_vision_codes {
            self.code_detector.detect(&buffer.image)?
        } else {
            Vec::new()
        };

        if self.config.enable_redaction {
            self.compliance_redactor
                .auto_censor(&mut buffer.image, &mut spans);
        }

        let layout_map = SpatialLayoutMap::from_spans(spans, buffer.dimensions());
        let formatted_text = layout_map.to_coordinate_formatted_text();

        let mut rag_applied = false;
        let mut rag_retrieved_chunks = Vec::new();
        let mut rag_context = String::new();

        if self.config.enable_rag {
            let mut retriever = self.rag_retriever.clone().unwrap_or_default();
            retriever.index_page(0, &layout_map);

            let query = format!("{document_id} {formatted_text}");
            let mut chunks = retriever.retrieve(&query, None);
            if chunks.is_empty()
                && !layout_map.is_empty()
                && let Some(first_line) = layout_map.lines.first()
            {
                chunks = retriever.retrieve(&first_line.text, None);
            }

            if !chunks.is_empty() {
                rag_applied = true;
                rag_retrieved_chunks = chunks;
                for chunk in &rag_retrieved_chunks {
                    rag_context.push_str(&chunk.text);
                    rag_context.push('\n');
                }
            }
        }

        let prompt_context = build_prompt_context(&formatted_text, &optical_codes, &rag_context);

        let schema = schemars::schema_for!(T);
        let (outcome, final_data, final_json, repair_attempts, domain_errors) = self
            .run_self_repair_loop::<T>(&prompt_context, &schema)
            .await?;

        let confidence = if outcome.is_strict() {
            0.95
        } else if outcome.is_soft() {
            0.75
        } else {
            0.20
        };

        let (routed_to_triage, triage_reasons) =
            if self.config.validation_mode == ValidationMode::Permissive {
                (false, Vec::new())
            } else {
                self.evaluate_triage(&layout_map, &final_json, confidence, &domain_errors)
            };

        Ok(ExtractionResult {
            document_id: document_id.to_string(),
            outcome,
            data: final_data,
            raw_json: final_json,
            confidence,
            optical_codes,
            formatted_text,
            repair_attempts,
            routed_to_triage,
            triage_reasons,
            rag_applied,
            rag_retrieved_chunks,
        })
    }

    /// Renders or loads raw source bytes into a single-page [`PageRasterBuffer`].
    pub fn render_or_load_source(
        &self,
        source: &DocumentSource,
    ) -> Result<PageRasterBuffer, DoculaPipelineError> {
        if source.is_office() {
            let routing_report = self.router.route_source(source)?;
            if let Some(PageRoute::BornDigital { text_layer, .. }) = routing_report.routes.first() {
                return self
                    .office_rasterizer
                    .render_spans(text_layer, 0, self.config.dpi)
                    .map_err(DoculaPipelineError::Preprocess);
            }
        }

        let (bytes, is_pdf) = load_source_payload(source)?;
        if is_pdf {
            let buffer = self
                .rasterizer
                .render_page(&bytes, 0, self.config.dpi)
                .map_err(DoculaPipelineError::Preprocess)?;
            Ok(buffer)
        } else {
            let dyn_img = image::load_from_memory(&bytes).map_err(|e| {
                DoculaPipelineError::ExecutionFailure(format!("Failed to decode image bytes: {e}"))
            })?;
            let buffer = PageRasterBuffer::new(0, dyn_img.to_rgba8(), self.config.dpi)
                .map_err(DoculaPipelineError::Preprocess)?;
            Ok(buffer)
        }
    }

    /// Executes the self-repair retry loop for constrained LLM extraction and domain validation.
    async fn run_self_repair_loop<T>(
        &self,
        prompt_context: &str,
        schema: &schemars::Schema,
    ) -> Result<
        (
            ValidationOutcome<T>,
            Option<T>,
            String,
            usize,
            Vec<ValidationError>,
        ),
        DoculaPipelineError,
    >
    where
        T: DocuValidate + DeserializeOwned + Serialize + Send + Sync + Clone,
    {
        let system_prompt = "You are a precise document extraction engine. Return strictly valid JSON matching the schema.";
        let mut user_prompt = prompt_context.to_string();
        let mut final_json = String::new();
        let mut last_parsed: Option<T> = None;
        let mut domain_errors = Vec::new();
        let mut attempts = 0;
        let mut strict_passed = false;

        for step in 0..self.config.max_repair_attempts {
            attempts = step + 1;
            let generated = self
                .llm_backend
                .generate_constrained(system_prompt, &user_prompt, schema)
                .await?;
            final_json = generated.clone();

            match serde_json::from_str::<T>(&generated) {
                Ok(parsed) => match parsed.validate_integrity() {
                    Ok(()) => {
                        last_parsed = Some(parsed);
                        domain_errors.clear();
                        strict_passed = true;
                        break;
                    }
                    Err(errs) => {
                        domain_errors = errs;
                        last_parsed = Some(parsed);
                        append_repair_feedback(&mut user_prompt, &domain_errors);
                    }
                },
                Err(syntax_err) => {
                    domain_errors =
                        vec![ValidationError::new("json_syntax", syntax_err.to_string())];
                    user_prompt.push_str(&format!(
                        "\n\nJSON SYNTAX ERROR: {syntax_err}\nPlease correct formatting."
                    ));
                }
            }
        }

        let outcome = if strict_passed && let Some(valid_data) = last_parsed.clone() {
            ValidationOutcome::Strict(valid_data)
        } else if let Some(soft_data) = last_parsed.clone() {
            ValidationOutcome::Soft {
                data: soft_data,
                validation_errors: domain_errors.clone(),
            }
        } else {
            ValidationOutcome::Error {
                raw_output: final_json.clone(),
                message: domain_errors
                    .first()
                    .map(|e| e.error_message.clone())
                    .unwrap_or_else(|| "Syntax or schema failure".to_string()),
            }
        };

        let final_data = match self.config.validation_mode {
            ValidationMode::Strict => {
                if strict_passed {
                    last_parsed
                } else {
                    None
                }
            }
            ValidationMode::Soft | ValidationMode::Permissive => last_parsed,
        };

        Ok((outcome, final_data, final_json, attempts, domain_errors))
    }

    /// Evaluates extraction results against the triage gate and optionally enqueues review items.
    fn evaluate_triage(
        &self,
        layout_map: &SpatialLayoutMap,
        final_json: &str,
        confidence: f32,
        domain_errors: &[ValidationError],
    ) -> (bool, Vec<String>) {
        let decision = self.triage_gate.evaluate(confidence, domain_errors);
        match decision {
            TriageDecision::Pass => (false, Vec::new()),
            TriageDecision::NeedsReview { reasons } => {
                let triage_item = TriageItem {
                    id: Uuid::now_v7(),
                    model_output: serde_json::from_str(final_json)
                        .unwrap_or(serde_json::Value::Null),
                    reasons: reasons.clone(),
                    spatial_layout: layout_map.clone(),
                    confidence,
                };
                self.triage_queue.enqueue(triage_item);
                (true, reasons)
            }
        }
    }
}

/// Appends validation failure feedback to prompt for LLM self-repair iteration.
fn append_repair_feedback(user_prompt: &mut String, domain_errors: &[ValidationError]) {
    user_prompt.push_str("\n\nINTEGRITY VALIDATION REPAIR REQUIRED:\n");
    for err in domain_errors {
        user_prompt.push_str(&format!("- [{}] {}\n", err.field_path, err.error_message));
    }
    user_prompt.push_str("Please correct these discrepancies and output valid JSON.");
}

/// Resolves byte slice and PDF format indicator from a [`DocumentSource`].
fn load_source_payload(source: &DocumentSource) -> Result<(Vec<u8>, bool), DoculaPipelineError> {
    match source {
        DocumentSource::PdfBytes(bytes) => Ok((bytes.clone(), true)),
        DocumentSource::PdfPath(path) => {
            let bytes = std::fs::read(path)?;
            Ok((bytes, true))
        }
        DocumentSource::ImageBytes { data, .. } => Ok((data.clone(), false)),
        DocumentSource::ImagePath(path) => {
            let bytes = std::fs::read(path)?;
            Ok((bytes, false))
        }
        DocumentSource::OfficeBytes { data, .. } => Ok((data.clone(), false)),
        DocumentSource::OfficePath { path, .. } => {
            let bytes = std::fs::read(path)?;
            Ok((bytes, false))
        }
        _ => Err(DoculaPipelineError::ExecutionFailure(
            "Batch sources must be processed via batch API".to_string(),
        )),
    }
}

/// Builds initial prompt context combining layout text, RAG context, and decoded optical codes.
fn build_prompt_context(
    formatted_text: &str,
    codes: &[OpticalCodeResult],
    rag_context: &str,
) -> String {
    let mut context = format!("DOCUMENT SPATIAL LAYOUT:\n{formatted_text}\n");
    if !rag_context.is_empty() {
        context.push_str("\nRETRIEVAL-AUGMENTED CONTEXT (RAG):\n");
        context.push_str(rag_context);
        context.push('\n');
    }
    if !codes.is_empty() {
        context.push_str("\nDECODED OPTICAL CODES & FINANCIAL PAYLOADS:\n");
        for code in codes {
            context.push_str(&format!(
                "- Format: {:?}, Raw: {}\n",
                code.code_type, code.raw_content
            ));
            if let Some(ref fin) = code.financial_payload {
                context.push_str(&format!("  Financial: {fin:?}\n"));
            }
        }
    }
    context
}

/// Fluent builder for constructing customized [`DoculaPipeline`] instances.
#[derive(Default)]
pub struct DoculaPipelineBuilder {
    config: PipelineConfig,
    router: Option<DocumentRouter>,
    ocr_engine: Option<Arc<dyn OcrEngine>>,
    llm_backend: Option<Arc<dyn LlmBackend>>,
    compliance_redactor: Option<ComplianceRedactor>,
    exemplar_pool: Option<ExemplarPool>,
    rag_retriever: Option<RagRetriever>,
}

impl DoculaPipelineBuilder {
    /// Overrides operational pipeline configuration.
    #[must_use]
    pub fn with_config(mut self, config: PipelineConfig) -> Self {
        self.config = config;
        self
    }

    /// Sets a custom document router instance.
    #[must_use]
    pub fn with_router(mut self, router: DocumentRouter) -> Self {
        self.router = Some(router);
        self
    }

    /// Sets the OCR detection and character recognition engine.
    #[must_use]
    pub fn with_ocr_engine(mut self, ocr_engine: Arc<dyn OcrEngine>) -> Self {
        self.ocr_engine = Some(ocr_engine);
        self
    }

    /// Sets the constrained language model inference backend.
    #[must_use]
    pub fn with_llm_backend(mut self, llm_backend: Arc<dyn LlmBackend>) -> Self {
        self.llm_backend = Some(llm_backend);
        self
    }

    /// Sets the compliance redactor.
    #[must_use]
    pub fn with_compliance_redactor(mut self, redactor: ComplianceRedactor) -> Self {
        self.compliance_redactor = Some(redactor);
        self
    }

    /// Sets the few-shot exemplar pool.
    #[must_use]
    pub fn with_exemplar_pool(mut self, pool: ExemplarPool) -> Self {
        self.exemplar_pool = Some(pool);
        self
    }

    /// Sets a pre-configured RAG retriever instance.
    #[must_use]
    pub fn with_rag_retriever(mut self, retriever: RagRetriever) -> Self {
        self.rag_retriever = Some(retriever);
        self
    }

    /// Builds the configured [`DoculaPipeline`].
    pub fn build(self) -> DoculaPipeline {
        DoculaPipeline {
            triage_gate: TriageGate::new(self.config.min_token_confidence),
            config: self.config,
            router: self.router.unwrap_or_default(),
            rasterizer: TinySkiaRasterizer::new(),
            office_rasterizer: OfficeRasterizer::new(),
            ocr_engine: self
                .ocr_engine
                .unwrap_or_else(|| Arc::new(MockOcrEngine::new())),
            code_detector: OpticalCodeDetector::new(),
            compliance_redactor: self.compliance_redactor.unwrap_or_default(),
            _exemplar_pool: self.exemplar_pool.unwrap_or_default(),
            triage_queue: TriageQueue::new(),
            llm_backend: self
                .llm_backend
                .unwrap_or_else(|| Arc::new(MockLlmBackend::new())),
            rag_retriever: self.rag_retriever,
        }
    }
}
